import { test, expect } from '@playwright/test';
import type { Gesture } from './input-adapter.ts';

test('S12 actual Chromium wheel, captured pan, context target and native editing route correctly', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/dev/fixtures/input-adapter.html');
  const root = page.getByRole('region', { name: 'Input view', exact: true }); const box = (await root.boundingBox())!;
  const gestures = async (): Promise<Gesture[]> => JSON.parse(await page.locator('#gestures').textContent() || '[]');
  const commands = async (): Promise<string[]> => JSON.parse(await page.locator('#commands').textContent() || '[]');
  await root.focus(); await page.mouse.move(box.x + 240, box.y + 100); await page.mouse.wheel(0, -400);
  await expect.poll(async () => JSON.parse(await page.locator('#view-state').textContent() || '{}').zoom).toBe(2);
  const zoomed = JSON.parse(await page.locator('#view-state').textContent() || '{}');
  expect(zoomed).toEqual({ zoom: 2, pan: { x: -240, y: -100 } });
  await page.keyboard.down('Space'); await page.mouse.move(box.x + 170, box.y + 170); await page.mouse.down();
  await page.mouse.move(box.x + box.width + 35, box.y + 180); await page.mouse.up(); await page.keyboard.up('Space');
  const pan = (await gestures()).filter((value): value is Extract<Gesture, { type: 'pan' }> => value.type === 'pan');
  expect(pan.reduce((sum, value) => sum + value.delta.x, 0)).toBe(box.width + 35 - 170);
  expect((await gestures()).some(value => value.type === 'pointer' && value.phase === 'down')).toBe(false);
  await page.mouse.move(box.x + 350, box.y + 220); await page.mouse.down(); await page.mouse.up();
  expect((await gestures()).filter(value => value.type === 'pointer' && ['down', 'up'].includes(value.phase)).map(value => value.type === 'pointer' && value.phase)).toEqual(['down', 'up']);
  await page.getByRole('button', { name: 'Reset demonstration' }).click();
  const target = page.getByText('Face 7', { exact: true }); await page.keyboard.down('Control'); await target.click(); await page.keyboard.up('Control');
  expect((await gestures()).some(value => value.type === 'pointer' && value.phase === 'down' && value.ctrl)).toBe(true);
  await target.click({ button: 'right' });
  expect((await gestures()).filter(value => value.type === 'context').at(-1)).toMatchObject({ type: 'context', targetId: 'face-7' });
  await page.getByRole('button', { name: 'Reset demonstration' }).click();
  const input = page.getByRole('textbox', { name: 'Native text' }); await input.click(); await page.keyboard.press('Control+A'); await page.keyboard.press('Control+C'); await page.keyboard.press('End'); await page.keyboard.press('Control+V');
  await expect(input).toHaveValue('alphaalpha'); expect(await commands()).toEqual([]);
  expect((await gestures()).some(value => value.type === 'pointer' && value.phase === 'down')).toBe(false);
  const nativeButton = page.getByRole('button', { name: 'Panel action', exact: true }); await nativeButton.focus();
  await page.keyboard.press('Control+Z'); expect(await commands()).toEqual(['edit.undo']);
  await page.keyboard.press('Enter'); await page.keyboard.press('Space'); await expect(nativeButton).toHaveAttribute('data-clicks', '2');
  await page.getByRole('button', { name: 'Reset demonstration' }).click();
  await page.getByRole('combobox', { name: 'Context', exact: true }).selectOption('timeline');
  await page.keyboard.down('Space'); await page.keyboard.down('Space'); await page.keyboard.up('Space'); await page.keyboard.press('ArrowRight');
  expect(await commands()).toEqual(['video.togglePlayback', 'video.stepForward']);
  await page.screenshot({ path: 'dev/evidence/S12-input-demo.png' }); await testInfo.attach('input-demo', { path: 'dev/evidence/S12-input-demo.png', contentType: 'image/png' });
  expect(errors).toEqual([]);
});
